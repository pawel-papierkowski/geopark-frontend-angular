/**
 * This script generates manifest - list of json files found for each language. Manifest is in 'src/shared/config/translation-manifest.ts'.
 * You need to run this script before every build or start. Use scripts.prestart and scripts.prebuild in package.json.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const i18nDir = join(import.meta.dirname, '..', 'public', 'i18n');
const outputFile = join(import.meta.dirname, '..', 'src', 'shared', 'config', 'translation-manifest.ts');

/**
 * Searches recursively for all json files.
 * @param dir Directory.
 * @param baseDir Base directory.
 * @returns Array of json files.
 */
function findJsonFiles(dir, baseDir) {
  const entries = readdirSync(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...findJsonFiles(fullPath, baseDir));
    } else if (entry.isFile() && extname(entry.name) === '.json') {
      const relativePath = relative(baseDir, fullPath);
      // Remove .json extension and normalize separators.
      files.push(relativePath.replace(/\.json$/, '').replace(/\\/g, '/'));
    }
  }

  return files.sort();
}

/**
 * Detect all languages. Any directory in `i18nDir` will be considered language. Name of directory is language code.
 * @param i18nDir Directory to use as root.
 * @returns List of directories.
 */
function discoverLanguages(i18nDir) {
  const entries = readdirSync(i18nDir, { withFileTypes: true });
  return entries
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

/** Generate actual manifest file. */
function generate() {
  const languages = discoverLanguages(i18nDir);
  if (languages.length === 0) throw new Error(`No language directories found in ${i18nDir}.`);

  const manifest = Object.create(null);

  for (const lang of languages) {
    const langDir = join(i18nDir, lang);
    const files = findJsonFiles(langDir, langDir);
    if (files.length === 0) throw new Error(`Language directory ${langDir} contains no JSON files.`);
    manifest[lang] = files;
  }

  const content = `// Auto-generated by script 'scripts/generate-i18n-manifest.mjs'.
// Do not edit manually.

export const languages = ${JSON.stringify(languages)} as const;

export const translationManifest = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<typeof languages[number], readonly string[]>;
`;

  writeFileSync(outputFile, content, 'utf-8');
  console.log(`Generated i18n manifest: ${languages.length} languages, ${Object.values(manifest).flat().length} files total.`);
}

generate();
