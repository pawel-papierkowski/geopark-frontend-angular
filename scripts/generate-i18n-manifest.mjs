/**
 * This script generates manifest - list of json files found for each language. Manifest is in 'src/core/i18n/translation-manifest.ts'.
 * You need to run this script before every build or start. Use scripts.prestart and scripts.prebuild in package.json.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const I18N_DIR = join(import.meta.dirname, '..', 'public', 'i18n');
const OUTPUT_FILE = join(import.meta.dirname, '..', 'src', 'core', 'i18n', 'translation-manifest.ts');

/**
 * Searches recursively for all json files.
 * @param dir Directory.
 * @param baseDir Base directory.
 * @returns Array of json files.
 */
function findJsonFiles(dir, baseDir) {
  const entries = readdirSync(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...findJsonFiles(fullPath, baseDir));
    } else if (entry.isFile() && extname(entry.name) === '.json') {
      const relativePath = relative(baseDir, fullPath);
      // Remove .json extension and normalize separators.
      files.push(relativePath.replace(/\.json$/, '').replace(/\\/g, '/'));
    }
  }

  return files.sort();
}

/**
 * Detect all languages. Any directory in /i18n will be considered language. Name of directory is language code.
 * @returns List of directories.
 */
function discoverLanguages() {
  const entries = readdirSync(I18N_DIR, { withFileTypes: true });
  return entries
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

/** Generate actual manifest file. */
function generate() {
  const languages = discoverLanguages();
  const manifest = {};

  for (const lang of languages) {
    const langDir = join(I18N_DIR, lang);
    manifest[lang] = findJsonFiles(langDir, langDir);
  }

  const content = `// Auto-generated by script 'scripts/generate-i18n-manifest.mjs'.
// Do not edit manually.

export const translationManifest: Record<string, string[]> = ${JSON.stringify(manifest, null, 2)};
`;

  writeFileSync(OUTPUT_FILE, content, 'utf-8');
  console.log(`Generated i18n manifest: ${Object.keys(manifest).length} languages, ${Object.values(manifest).flat().length} files total.`);
}

generate();
